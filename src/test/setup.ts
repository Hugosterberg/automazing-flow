import "@testing-library/jest-dom";

// Server-provider test files opt into `// @vitest-environment node`, where
// there is no `window`. Only install the DOM stub when a window exists.
if (typeof window !== "undefined") {
  Object.defineProperty(window, "matchMedia", {
    writable: true,
    value: (query: string) => ({
      matches: false,
      media: query,
      onchange: null,
      addListener: () => {},
      removeListener: () => {},
      addEventListener: () => {},
      removeEventListener: () => {},
      dispatchEvent: () => {},
    }),
  });
}
